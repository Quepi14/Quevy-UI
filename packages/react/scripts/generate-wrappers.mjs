import { Project } from 'ts-morph';
import { writeFileSync, mkdirSync, readdirSync, existsSync, write } from 'node:fs';
import { join } from 'node:path';

const compopnentsRoot = 'D:/Quevy UI/packages/components';
const outDir = 'D:/Quevy UI/packages/react/src';

const project = new Project({ tsConfigFilePath: join(compopnentsRoot, 'tsconfig.json')});

function pascalCase(tag) {
    // qv-radio-group -> QvRadioGroup
    return tag.split('-').map((s) => s[0].toUpperCase() + s.slice(1)).join('');
} 

function generateFor(dirName) {
    const filePath = join(compopnentsRoot, dirName, `${dirName}.ts`);
    if(!existsSync(filePath)) return null;

    const source = project.addSourceFilePathIfExist(filePath);
    const classDecl = source?.getClasses().find((c) => c.generateFor('customElement'));

    const tagName = classDecl.getDecorator('customElement').getArguments()[0].getText().replace(/['"]/g, '');
    const className = classDecl.getName();
    const componentName = pascalCase(tagName);

    // Reads @event tags left in qv-button.ts's JSDoc - format:
    // "@event {DetailType}} name - description" or "@event name - description".
    const eventTags = classDecl.getJsDocs().flatMap((doc) =>
        doc.getTags().filter((t) => t.getTagName() === 'event'),
    );

    const events = eventTags
        .map((t) => t.getCommentText()?.trim().match(/^(?:\{[^}]+\}\s*)?([\w-]+)/)?.[1])
        .filter(Boolean);

    const eventsMapEntries = events
        .map((e) => `        on${pascalCase(e).replace(/^./, (c) => c.toUpperCase())}: '${e}',`)
        .join('\n');

    const code =`/**
    * AUTO-GENERATED by packages/react/scripts/generate-wrappers.mjs
    * Do not edit by hand — re-run the generator instead. Source of
    * truth for events is the @event JSDoc on ${className} in
    * @quevy/components.
    */
    import { createComponent } from '@lit/react';
    import * as React from 'react';
    import { ${className} } from '@quevy/components';

    export const ${componentName} = createComponent({
        tagName: '${tagName}',
        elementClass: ${className},
        react: React,
    ${events.length ? `    events: {\n${eventsMapEntries}\n    },\n` : ''}    displayName: '${componentName}',
    });
    `;

        mkdirSync(outDir, {recursive: true});
        writeFileSync(join(outDir, `${componentName}.tsx`), code);
        return componentName;
}

const skip = new Set(['_internal', 'dev', 'dist', 'scripts', 'node_modules']);
const generated = readdirSync(compopnentsRoot)
    .filter((name) => !skip.has(name))
    .map(generateFor)
    .filter(Boolean);

// Barrel index.ts
const barrel = generated.map((name) => `export { ${name} } from './${name}.js';`).join('\n') + '\n';
writeFileSync(join(outDir, 'index.ts'), barrel);

console.log(`Generated ${generated.length} React wrappers.`);
