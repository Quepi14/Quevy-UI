import { Project } from 'ts-morph';
import {
    existsSync,
    mkdirSync,
    readdirSync,
    writeFileSync,
} from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const __filename = fileURLToPath(import.meta.url);
const __dirname = dirname(__filename);

/**
 * ----------------------------------------------------------
 * QUEVY UI — React Wrapper Generator
 * ----------------------------------------------------------
 *
 * Generates React wrappers for Quevy UI Web Components.
 *
 * Source of truth:
 *   packages/components
 *
 * Generated output:
 *   packages/react/src
 *
 * Example:
 *   qv-button
 *      ↓
 *   QvButton.tsx
 *
 *   qv-radio-group
 *      ↓
 *   QvRadioGroup.tsx
 *
 * Events are inferred from @event JSDoc tags on the
 * corresponding Web Component class.
 * ----------------------------------------------------------
 */

const componentsRoot = resolve(__dirname, '../../components');
const outDir = resolve(__dirname, '../src');

const componentsTsConfig = join(componentsRoot, 'tsconfig.json');

if (!existsSync(componentsTsConfig)) {
    throw new Error(
        `Unable to find components tsconfig: ${componentsTsConfig}`,
    );
}

const project = new Project({
    tsConfigFilePath: componentsTsConfig,
});

/**
 * Convert a custom element tag name to a React component name.
 *
 * qv-button      → QvButton
 * qv-tooltip     → QvTooltip
 * qv-radio-group → QvRadioGroup
 */
function pascalCase(value) {
    return value
        .split('-')
        .filter(Boolean)
        .map(
            (part) =>
                part.charAt(0).toUpperCase() + part.slice(1),
        )
        .join('');
}

/**
 * Extract the custom element tag name from
 * @customElement('qv-button').
 */
function getCustomElementTag(classDecl) {
    const decorator = classDecl.getDecorator('customElement');

    if (!decorator) {
        return null;
    }

    const argument = decorator.getArguments()[0];

    if (!argument) {
        return null;
    }

    const text = argument.getText().trim();

    return text.replace(/^['"]|['"]$/g, '');
}

/**
 * Extract event names from @event JSDoc tags.
 *
 * Supported:
 *
 * @event change - description
 * @event {CustomEvent<ChangeDetail>} change - description
 */
function getEvents(classDecl) {
    const eventTags = classDecl
        .getJsDocs()
        .flatMap((doc) =>
            doc
                .getTags()
                .filter((tag) => tag.getTagName() === 'event'),
        );

    const events = eventTags
        .map((tag) => {
            const comment = tag.getCommentText()?.trim();

            if (!comment) {
                return null;
            }

            const match = comment.match(
                /^(?:\{[^}]+\}\s*)?([\w-]+)/,
            );

            return match?.[1] ?? null;
        })
        .filter(Boolean);

    return [...new Set(events)];
}

/**
 * Generate the events object used by @lit/react.
 *
 * Example:
 *
 * change
 * input
 *
 * becomes:
 *
 * events: {
 *     onChange: 'change',
 *     onInput: 'input',
 * }
 */
function generateEventsMap(events) {
    if (events.length === 0) {
        return '';
    }

    const entries = events
        .map(
            (event) =>
                `        on${pascalCase(event)}: '${event}',`,
        )
        .join('\n');

    return `    events: {\n${entries}\n    },\n`;
}

/**
 * Generate one React wrapper from a component directory.
 */
function generateFor(dirName) {
    const componentFile = join(
        componentsRoot,
        dirName,
        `${dirName}.ts`,
    );

    if (!existsSync(componentFile)) {
        return null;
    }

    const source = project.addSourceFileAtPathIfExists(
        componentFile,
    );

    if (!source) {
        console.warn(
            `[skip] Unable to load source: ${componentFile}`,
        );

        return null;
    }

    const classDecl = source
        .getClasses()
        .find((classDeclaration) =>
            classDeclaration.getDecorator('customElement'),
        );

    if (!classDecl) {
        console.warn(
            `[skip] No @customElement class found: ${componentFile}`,
        );

        return null;
    }

    const className = classDecl.getName();

    if (!className) {
        console.warn(
            `[skip] Component class has no name: ${componentFile}`,
        );

        return null;
    }

    const tagName = getCustomElementTag(classDecl);

    if (!tagName) {
        console.warn(
            `[skip] Unable to resolve custom element tag: ${componentFile}`,
        );

        return null;
    }

    const componentName = pascalCase(tagName);
    const events = getEvents(classDecl);
    const eventsMap = generateEventsMap(events);

    const code = `/**
 * AUTO-GENERATED by packages/react/scripts/generate-wrappers.mjs
 *
 * Do not edit this file by hand.
 * Re-run the generator instead.
 *
 * Source of truth:
 *   @quevy/components
 */

import { createComponent } from '@lit/react';
import * as React from 'react';

import { ${className} as ${className}Element } from '@quevy/components';

export const ${componentName} = createComponent({
    tagName: '${tagName}',
    elementClass: ${className}Element,
    react: React,
${eventsMap}    displayName: '${componentName}',
});
`;

    mkdirSync(outDir, { recursive: true });

    const outputFile = join(
        outDir,
        `${componentName}.tsx`,
    );

    writeFileSync(outputFile, code, 'utf8');

    console.log(
        `[generated] ${componentName}.tsx`,
    );

    return componentName;
}

/**
 * Directories that are not Quevy UI components.
 */
const skip = new Set([
    '_internal',
    'dev',
    'dist',
    'scripts',
    'node_modules',
]);

/**
 * Find component directories and generate wrappers.
 */
const generated = readdirSync(componentsRoot, {
    withFileTypes: true,
})
    .filter((entry) => entry.isDirectory())
    .map((entry) => entry.name)
    .filter((name) => !skip.has(name))
    .map(generateFor)
    .filter(Boolean);

/**
 * Generate barrel index.ts.
 *
 * The generated JavaScript files are referenced with .js
 * because the package uses NodeNext module resolution.
 */
const barrel = `${generated
    .sort()
    .map(
        (name) =>
            `export { ${name} } from './${name}.js';`,
    )
    .join('\n')}\n`;

mkdirSync(outDir, { recursive: true });

writeFileSync(
    join(outDir, 'index.ts'),
    barrel,
    'utf8',
);

console.log('');
console.log(
    `Generated ${generated.length} React wrapper(s).`,
);